def icon_svg(name, css_class='icon'):
    """Inline ``<svg>`` for a sprite name ('' when the name is unknown)."""
    if name not in ICON_NAMES:
        return ''
    return '<svg class="%s" aria-hidden="true"><use href="#i-%s"></use></svg>' % (
        css_class,
        name,
    )
